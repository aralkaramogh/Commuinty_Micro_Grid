function s = proto_encode_meas(seq, t_ms, m)
% PROTO_ENCODE_MEAS  MATLAB -> ESP32 measurement line (see docs/protocol.md).
s = sprintf(['M,%d,%d,%.3f,%.4f,%.3f,%.4f,%.3f,%.2f,%.2f,%.2f,%.2f,%.6f,%d,' ...
             '%.2f,%.2f,%.2f,%d,%d,%d,%d,%.1f,%d,%.3f'], ...
    seq, t_ms, m.v_grid, m.f_grid, m.v_c, m.f_mg, m.dtheta, m.p_pcc, m.q_pcc, ...
    m.p_bess, m.q_bess, m.soc, m.bess_status, m.p_cl, m.q_cl, m.p_cpv, m.fb, ...
    m.card_house, m.card_uid, m.ai.valid, m.ai.p_bess, m.ai.shed_mask, m.ai.price);
s = [s, sprintf(',%.3f,%.4f,%.2f,%.2f,%.2f,%.2f', ...
    [m.v_h; m.i_h; m.p_load; m.q_load; m.p_pv; m.q_pv])];
end
