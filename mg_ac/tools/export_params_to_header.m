function export_params_to_header(P, out_file)
% EXPORT_PARAMS_TO_HEADER  Write firmware/include/config.h from ac_params.m so the
% ESP32 uses bit-identical constants (doubles printed with %.17g).
root = fileparts(fileparts(mfilename('fullpath')));
if nargin < 2, out_file = fullfile(root, 'firmware', 'include', 'config.h'); end
C = P.ctrl; H = P.house; n = P.n_house; b = P.bess;
fid = fopen(out_file, 'w'); c = onCleanup(@() fclose(fid));
w = @(varargin) fprintf(fid, varargin{:});
d = @(name, v) w('static const double %-16s = %.17g;\n', name, v);
i = @(name, v) w('static const int    %-16s = %d;\n', name, v);
arr = @(v, fmt) strjoin(compose(fmt, v), ', ');
w('// config.h - AUTO-GENERATED by tools/export_params_to_header.m from params/ac_params.m\n');
w('// DO NOT EDIT BY HAND.\n#pragma once\n#include <stdint.h>\n\n');
w('#define N_HOUSES %d\n#define SERIAL_BAUD %d\n\n', n, P.sim.baud);
d('DT_S', P.sim.dt); d('V_NOM', P.ac.V_nom);
d('BESS_P_DIS', b.P_dis_max); d('BESS_P_CH', b.P_ch_max); d('BESS_S', b.S_rated);
d('V_OK_LO', C.V_ok_lo); d('V_OK_HI', C.V_ok_hi); d('F_OK_LO', C.F_ok_lo); d('F_OK_HI', C.F_ok_hi);
d('V_LOST', C.V_lost); i('N_ABN', C.N_abn); i('N_BOOT', C.N_boot); i('N_GRID_STABLE', C.N_grid_stable);
d('DV_SYNC', C.DV_sync); d('DF_SYNC', C.DF_sync); d('DTH_SYNC', C.DTH_sync);
d('F_UFLS', C.F_ufls); d('T_UF_HOLD', C.T_uf_hold); d('T_UF_STEP', C.T_uf_step); d('UF_RESTORE', C.UF_restore);
d('SOC_HYST', C.soc_hyst); d('SOC_RESERVE', C.soc_reserve); d('SOC_AI_MIN', C.soc_ai_min);
d('SOC_CH_STOP', C.soc_ch_stop); d('P_RECHARGE', C.P_recharge); d('I_TRIP', C.I_trip);
i('N_OC', C.N_oc); i('N_RETRY', C.N_retry); i('STRIKES_MAX', C.strikes_max); i('N_STRIKE_CLEAR', C.N_strike_clear);
d('PRICE_DEFAULT', C.price_default); d('PRICE_MIN', C.price_min); d('PRICE_MAX', C.price_max);
d('SELL_RATIO', C.sell_ratio); d('CREDIT_RESTORE', C.credit_restore); d('CARD_TOPUP', C.card_topup);
i('CARD_BAD_MAX', C.card_bad_max); i('N_CARD_LOCK', C.N_card_lock); d('T_AI_TIMEOUT', C.T_ai_timeout);
i('TELEMETRY_EVERY', C.telemetry_every);
w('\n// houses (index 0 = %s)\n', H(1).id);
w('__attribute__((unused)) static const char* HOUSE_ID[N_HOUSES] = {%s};\n', arr(string({H.id}), '"%s"'));
w('static const double   HOUSE_P_FLEX[N_HOUSES]   = {%s};\n', arr([H.P_flex], '%.17g'));
w('static const double   HOUSE_SHED_SOC[N_HOUSES] = {%s};\n', arr([H.shed_soc], '%.17g'));
w('static const double   HOUSE_CREDIT0[N_HOUSES]  = {%s};\n', arr([H.credit0], '%.17g'));
w('static const uint32_t HOUSE_CARD_UID[N_HOUSES] = {%s};\n\n', arr([H.card_uid], '%uu'));
w('// ESP32 pins (ESP32-S3 boards get their own safe pins automatically)\n#if defined(CONFIG_IDF_TARGET_ESP32S3)\n');
w('#define LED_GRID %d\n#define LED_ISLAND %d\n#define LED_SHED %d\n#define LED_FAULT %d\n#define ESTOP_PIN %d\n#else\n', ...
  P.hw.s3_led_grid, P.hw.s3_led_island, P.hw.s3_led_shed, P.hw.s3_led_fault, P.hw.s3_estop_pin);
w('#define LED_GRID %d\n#define LED_ISLAND %d\n#define LED_SHED %d\n#define LED_FAULT %d\n#define ESTOP_PIN %d\n#endif\n', ...
  P.hw.led_grid, P.hw.led_island, P.hw.led_shed, P.hw.led_fault, P.hw.estop_pin);
end
