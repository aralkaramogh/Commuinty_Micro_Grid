function export_params_to_header(p, out_file)
% EXPORT_PARAMS_TO_HEADER  Generates firmware/include/config.h from MATLAB params.
% Ensures MATLAB simulation and ESP32 firmware share identical constants.
if nargin < 2; out_file = fullfile('firmware','include','config.h'); end
if ~exist(fileparts(out_file),'dir'); mkdir(fileparts(out_file)); end

fid = fopen(out_file, 'w');
fprintf(fid, '// config.h - AUTO-GENERATED by tools/export_params_to_header.m\n');
fprintf(fid, '// DO NOT EDIT MANUALLY - edit params/dc_microgrid_params.m and re-run\n');
fprintf(fid, '// Generated: %s\n\n', datestr(now));
fprintf(fid, '#pragma once\n');
fprintf(fid, '#include <stdint.h>\n\n');

fprintf(fid, '// ---- Bus Configuration ----\n');
fprintf(fid, '#define BUS_CONFIG_A %d\n', p.cfg.bus=='A');
fprintf(fid, '#define V_NOM_V      %.4ff\n', p.V_nom);
fprintf(fid, '#define V_MAX_V      %.4ff\n', p.V_max);
fprintf(fid, '#define V_MIN_V      %.4ff\n', p.V_min);
fprintf(fid, '#define V_TRIP_OV    %.4ff\n', p.V_trip_ov);
fprintf(fid, '#define V_TRIP_UV    %.4ff\n', p.V_trip_uv);

fprintf(fid, '\n// ---- Control Timing ----\n');
fprintf(fid, '#define TS_FAST_MS   %.1ff  // Fast loop period [ms]\n', p.ctrl.Ts_fast*1e3);
fprintf(fid, '#define TS_FSM_MS    %.1ff  // FSM period [ms]\n',  p.ctrl.Ts_fsm*1e3);
fprintf(fid, '#define PWM_FREQ_HZ  %d\n', round(p.ctrl.f_pwm));

fprintf(fid, '\n// ---- Soft-Start ----\n');
fprintf(fid, '#define SS_T_RAMP_S  %.3ff\n', p.ss.T_ramp);
fprintf(fid, '#define SS_I_LIMIT_A %.4ff\n', p.ss.I_limit);
fprintf(fid, '#define SS_DDUTY     %.6ff  // duty step per fast tick\n', p.ss.dDuty_step);

fprintf(fid, '\n// ---- Storage Emulator ----\n');
fprintf(fid, '#define STOR_V_OC     %.4ff\n', p.stor.V_oc);
fprintf(fid, '#define STOR_R_SER    %.4ff\n', p.stor.R_series);
fprintf(fid, '#define STOR_I_LIM    %.4ff\n', p.stor.I_limit);
fprintf(fid, '#define STOR_CAP_AH   %.4ff\n', p.stor.capacity_Ah);
fprintf(fid, '#define SOC_INIT      %.4ff\n', p.stor.SOC_init);
fprintf(fid, '#define SOC_MIN       %.4ff\n', p.stor.SOC_min);
fprintf(fid, '#define SOC_CRIT      %.4ff\n', p.stor.SOC_crit);
fprintf(fid, '#define SOC_START_MIN %.4ff\n', p.stor.SOC_start_min);
fprintf(fid, '#define ETA_DISCHARGE %.4ff\n', p.stor.eta_discharge);

fprintf(fid, '\n// ---- ACS712 Sensor ----\n');
fprintf(fid, '#define ACS_SENS_VA   %.4ff  // V/A sensitivity at ACS output\n', p.sens.acs712.sensitivity);
fprintf(fid, '#define ACS_OFFSET_V  %.4ff  // Midpoint at I=0\n', p.sens.acs712.V_offset);
fprintf(fid, '#define ACS_DIV_RATIO %.4ff  // Resistor divider (to ADC)\n', p.sens.acs712.div_ratio);
fprintf(fid, '#define ACS_GAIN_ADC  %.6ff  // V/A at ADC pin\n', p.sens.acs712.gain_adc);
fprintf(fid, '#define ACS_OFFSET_ADC %.4ff // V at ADC with I=0\n', p.sens.acs712.offset_adc);
fprintf(fid, '#define ACS_OVERSAMPLE %d\n', p.sens.acs712.n_oversample);

fprintf(fid, '\n// ---- Voltage Sensor ----\n');
fprintf(fid, '#define VSENS_DIV     %.4ff  // 1/5 divider\n', p.sens.vsens.div_ratio);

fprintf(fid, '\n// ---- ADC ----\n');
fprintf(fid, '#define ADC_VREF      %.4ff\n', p.adc.V_ref);
fprintf(fid, '#define ADC_COUNTS    %d\n', p.adc.counts_max);
fprintf(fid, '#define ADC_LSB_V     %.7ff\n', p.adc.LSB);

fprintf(fid, '\n// ---- FSM Timing ----\n');
fprintf(fid, '#define T_BLACKOUT_CONFIRM_S  %.4ff\n', p.fsm.T_blackout_confirm);
fprintf(fid, '#define T_STABLE_MIN_S        %.4ff\n', p.fsm.T_stable_min);
fprintf(fid, '#define T_STABLE_DWELL_S      %.4ff\n', p.fsm.T_stable_dwell);
fprintf(fid, '#define T_LOAD_STEP_SETTLE_S  %.4ff\n', p.fsm.T_load_step_settle);
fprintf(fid, '#define V_STABLE_BAND         %.4ff\n', p.fsm.V_stable_band);
fprintf(fid, '#define V_BLACKOUT_THRESH     %.4ff\n', p.fsm.V_blackout_thresh);
fprintf(fid, '#define AUTH_LOCKOUT_SCANS    %d\n',    p.fsm.auth_lockout_scans);
fprintf(fid, '#define AUTH_LOCKOUT_TIME_S   %.1ff\n', p.fsm.auth_lockout_time);
fprintf(fid, '#define WDT_TIMEOUT_S         %.1ff\n', p.fsm.watchdog_timeout);
fprintf(fid, '#define RETRY_MAX             %d\n',    p.fsm.retry_max);
fprintf(fid, '#define RETRY_BACKOFF_BASE_S  %.1ff\n', p.fsm.retry_backoff_base);

fprintf(fid, '\n// ---- Protection ----\n');
fprintf(fid, '#define I_OC_HARD_A    %.4ff\n', p.prot.I_oc_hard);
fprintf(fid, '#define I_OC_SOFT_A    %.4ff\n', p.prot.I_oc_soft);
fprintf(fid, '#define I2T_LIMIT      %.4ff\n', p.prot.I2t_limit);
fprintf(fid, '#define V_OV_TRIP      %.4ff\n', p.prot.V_ov_trip);
fprintf(fid, '#define T_OC_TRIP_S       %.4ff\n', p.prot.t_oc_trip);
fprintf(fid, '#define I_SW_EXPECT_MIN_A %.4ff\n', p.prot.I_sw_expect_min);
fprintf(fid, '#define T_SW_MISMATCH_S   %.4ff\n', p.prot.t_sw_mismatch);
fprintf(fid, '#define SENSOR_FREEZE_S   %.4ff\n', p.prot.sensor_freeze_time);
fprintf(fid, '#define STOR_I_INRUSH_MAX %.4ff\n', p.stor.I_inrush_max);
fprintf(fid, '#define V_UV_TRIP      %.4ff\n', p.prot.V_uv_trip);

fprintf(fid, '\n// ---- Restoration ----\n');
fprintf(fid, '#define REST_K_COLD    %.4ff\n', p.rest.k_cold);
fprintf(fid, '#define REST_T_BLAME_S         %.4ff\n', p.rest.t_blame);
fprintf(fid, '#define REST_MAX_STRIKES       %d\n',    p.rest.max_strikes);
fprintf(fid, '#define REST_T_STRIKE_CLEAR_S  %.4ff\n', p.rest.t_strike_clear);
fprintf(fid, '#define REST_T_SHED_HOLDOFF_S  %.4ff\n', p.rest.t_shed_holdoff);
fprintf(fid, '#define REST_MARGIN    %.4ff\n', p.rest.headroom_margin);
fprintf(fid, '#define REST_ISRC_FRAC %.4ff\n', p.rest.I_src_max_frac);

fprintf(fid, '\n// ---- Loads ----\n');
for i = 1:4
    fprintf(fid, '#define LOAD%d_R_OHM   %.2ff\n', i, p.load(i).R);
    fprintf(fid, '#define LOAD%d_P_NOM_W %.4ff\n', i, p.load(i).P_nom);
    fprintf(fid, '#define LOAD%d_INRUSH  %.2ff\n', i, p.load(i).inrush);
    fprintf(fid, '#define LOAD%d_SOC_MIN %.4ff\n', i, p.load(i).SOC_min_req);
end

fprintf(fid, '\n// ---- GPIO Pins ----\n');
fprintf(fid, '#define PIN_VBUS    %d\n', p.pins.V_bus);
fprintf(fid, '#define PIN_VPV     %d\n', p.pins.V_pv);
fprintf(fid, '#define PIN_ISRC    %d\n', p.pins.I_src);
fprintf(fid, '#define PIN_ILOAD   %d\n', p.pins.I_load);
fprintf(fid, '#define PIN_SRC_SW  %d\n', p.pins.SRC_SW);
fprintf(fid, '#define PIN_PV_SW   %d\n', p.pins.PV_SW);
fprintf(fid, '#define PIN_LOAD1   %d\n', p.pins.LOAD1);
fprintf(fid, '#define PIN_LOAD2   %d\n', p.pins.LOAD2);
fprintf(fid, '#define PIN_LOAD3   %d\n', p.pins.LOAD3);
fprintf(fid, '#define PIN_LOAD4   %d\n', p.pins.LOAD4);
fprintf(fid, '#define PIN_RC522_CS   %d\n', p.pins.RC522_CS);
fprintf(fid, '#define PIN_RC522_SCK  %d\n', p.pins.RC522_SCK);
fprintf(fid, '#define PIN_RC522_MOSI %d\n', p.pins.RC522_MOSI);
fprintf(fid, '#define PIN_RC522_MISO %d\n', p.pins.RC522_MISO);
fprintf(fid, '#define PIN_RC522_RST  %d\n', p.pins.RC522_RST);
fprintf(fid, '#define PIN_LED     %d\n', p.pins.LED_status);
fprintf(fid, '#define PIN_BUZZER  %d\n', p.pins.BUZZER);

fprintf(fid, '\n// ---- Telemetry ----\n');
fprintf(fid, '#define TELEM_BAUD  %d\n', p.telem.baud);
fprintf(fid, '#define TELEM_PERIOD_MS %.0ff\n', p.telem.Ts*1e3);

fprintf(fid, '\n// ---- MPPT ----\n');
fprintf(fid, '#define MPPT_DI_STEP   %.4ff\n', p.mppt.dI_step);
fprintf(fid, '#define MPPT_PERIOD_S  %.4ff\n', p.mppt.period);
fprintf(fid, '#define PV_V_DIODE     %.4ff\n', p.pv.V_diode);
fprintf(fid, '#define PV_CONN_MARGIN %.4ff\n', p.pv.connect_margin);

fprintf(fid, '\n// ---- IIR Filter ----\n');
fprintf(fid, '#define IIR_ALPHA      %.6ff  // sensor smoothing coefficient\n', p.filt.alpha_sens);

fprintf(fid, '\n// ---- Firmware Version ----\n');
fprintf(fid, '#define FW_VERSION_MAJOR 1\n');
fprintf(fid, '#define FW_VERSION_MINOR 0\n');
fprintf(fid, '#define FW_BUILD_DATE "%s"\n', datestr(now,'yyyy-mm-dd'));

fclose(fid);
fprintf('[export] Written %s (%d bytes)\n', out_file, dir(out_file).bytes);
end
