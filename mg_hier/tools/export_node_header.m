function export_node_header(P, out_file)
% EXPORT_NODE_HEADER  Write firmware_node/mg_node/config_node.h from hier_params.m
% so the node ESP32s use bit-identical constants (doubles printed with %.17g).
root = fileparts(fileparts(mfilename('fullpath')));
if nargin < 2, out_file = fullfile(root, 'firmware_node', 'mg_node', 'config_node.h'); end
N = P.node; b = P.bess;
fid = fopen(out_file, 'w'); c = onCleanup(@() fclose(fid));
w = @(varargin) fprintf(fid, varargin{:});
d = @(name, v) w('static const double %-15s = %.17g;\n', name, v);
i = @(name, v) w('static const int    %-15s = %d;\n', name, v);
w('// config_node.h - AUTO-GENERATED by tools/export_node_header.m from params/hier_params.m\n');
w('// DO NOT EDIT BY HAND.\n#pragma once\n\n#define SERIAL_BAUD %d\n\n', P.sim.baud);
d('DT_S', P.sim.dt); i('N_COMM_LOST', N.N_comm_lost);
d('I_TRIP', N.I_trip); i('N_OC', N.N_oc); i('N_RETRY', N.N_retry);
i('STRIKES_MAX', N.strikes_max); i('N_STRIKE_CLEAR', N.N_strike_clear);
d('SOC_FLOOR', N.soc_floor); d('SOC_CH_STOP', N.soc_ch_stop);
d('BESS_P_DIS', b.P_dis_max); d('BESS_P_CH', b.P_ch_max); d('BESS_S', b.S_rated);
d('BESS_V_DC_NOM', b.V_dc_nom);   % LCD read-out only
w('\n// LED and E-stop pins (ESP32-S3 boards get their own safe pins automatically)\n');
w('#if defined(CONFIG_IDF_TARGET_ESP32S3)\n');
w('#define LED_A %d\n#define LED_B %d\n#define LED_C %d\n#define LED_D %d\n#define ESTOP_PIN %d\n#else\n', ...
  P.hw.s3_led_a, P.hw.s3_led_b, P.hw.s3_led_c, P.hw.s3_led_d, P.hw.s3_estop_pin);
w('#define LED_A %d\n#define LED_B %d\n#define LED_C %d\n#define LED_D %d\n#define ESTOP_PIN %d\n#endif\n', ...
  P.hw.led_a, P.hw.led_b, P.hw.led_c, P.hw.led_d, P.hw.estop_pin);
clear c                                         % closes the file (onCleanup)
% the LCD sketch is the same node core + a display: keep its copies in step
lcd = fullfile(root, 'firmware_node', 'mg_node_lcd');
if exist(lcd, 'dir')
    for f = {'node.h', 'node.cpp'}, copyfile(fullfile(root, 'firmware_node', 'mg_node', f{1}), fullfile(lcd, f{1})); end
    copyfile(out_file, fullfile(lcd, 'config_node.h'));
end
end
