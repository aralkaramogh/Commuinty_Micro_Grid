function make_mosquitto_files(out_dir)
% MAKE_MOSQUITTO_FILES  Write the Pi broker config + ACL from pi/pi_acl.m (the
% same rules the simulation tests). Copy to the Pi:
%   sudo cp mg.conf /etc/mosquitto/conf.d/mg.conf ; sudo cp acl /etc/mosquitto/acl
if nargin < 1, out_dir = fullfile(fileparts(fileparts(mfilename('fullpath'))), 'docs', 'mosquitto'); end
if ~exist(out_dir, 'dir'), mkdir(out_dir); end
writelines(["# mg.conf - generated by tools/make_mosquitto_files.m"; "listener 1883"; ...
            "allow_anonymous false"; "password_file /etc/mosquitto/passwd"; "acl_file /etc/mosquitto/acl"], ...
           fullfile(out_dir, 'mg.conf'));
R = pi_acl(); s = "# acl - generated by tools/make_mosquitto_files.m from pi/pi_acl.m";
users = unique({R(~strcmp({R.user}, '*')).user}, 'stable');
for u = users
    s(end+1) = ""; s(end+1) = "user " + u{1}; %#ok<AGROW>
    for k = find(strcmp({R.user}, u{1})), s(end+1) = "topic " + R(k).access + " " + R(k).topic; end %#ok<AGROW>
end
s(end+1) = ""; s(end+1) = "# every user: only its own house (user name = house id, e.g. H1)";
for k = find(strcmp({R.user}, '*')), s(end+1) = "pattern " + R(k).access + " " + R(k).topic; end %#ok<AGROW>
writelines(s(:), fullfile(out_dir, 'acl'));
end
